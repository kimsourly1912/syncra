// Writes app/api/generated/endpoints.gen.ts: every Admin operation as `'METHOD /path'`, mapped
// to the request type @hey-api/typescript generated for it (path, query, and body). The client
// types `api.get('/admin/...', { path, query, body })` from this map. Runs after `openapi-ts`
// in `pnpm --filter admin api:gen`.
import { readFile, writeFile } from 'node:fs/promises'

const METHODS = ['get', 'post', 'put', 'patch', 'delete']
const ADMIN = /^\/admin\//

const spec = JSON.parse(await readFile(new URL('../openapi/syncra.json', import.meta.url), 'utf8'))
const types = await readFile(new URL('../app/api/generated/types.gen.ts', import.meta.url), 'utf8')

// @hey-api/typescript names a request type after its operationId: `getMyProfile_1` → `GetMyProfile1Data`.
const typeName = operationId => `${operationId.split(/[^A-Za-z0-9]+/).filter(Boolean).map(word => word[0].toUpperCase() + word.slice(1)).join('')}Data`

const entries = []
const multipart = []
const unenveloped = []
const missing = []

// The body a successful call answers with, or undefined when the spec doesn't describe one.
const successSchema = operation => Object.values(operation.responses?.['200']?.content ?? {})[0]?.schema

// A described body without the envelope's `success` flag (`SaleRequestListingResponse`). A response
// the spec leaves out stays enveloped (the client's default), so a refusal is still read. Files
// (`format: binary`) go through `api.download`, which never unwraps.
const resolve = schema => (schema?.$ref ? spec.components.schemas[schema.$ref.split('/').pop()] : schema)
const isUnenveloped = (schema) => {
  if (!schema || schema.format === 'binary') return false
  return !('success' in (resolve(schema)?.properties ?? {}))
}

for (const [path, item] of Object.entries(spec.paths)) {
  if (!ADMIN.test(path)) continue
  for (const method of METHODS) {
    const operation = item[method]
    if (!operation) continue
    const key = `${method.toUpperCase()} ${path}`
    const name = typeName(operation.operationId)
    // Same name, same URL: guards against a naming change in the generator mapping the wrong operation.
    if (!new RegExp(`export type ${name} = \\{[^]*?url: '${path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}';`).test(types)) missing.push(`${key} → ${name}`)
    entries.push([key, name])
    if (operation.requestBody?.content?.['multipart/form-data']) multipart.push(key)
    if (isUnenveloped(successSchema(operation))) unenveloped.push(key)
  }
}

if (missing.length) {
  console.error(`No generated request type for:\n  ${missing.join('\n  ')}\nCheck how @hey-api/typescript names operations.`)
  process.exit(1)
}

entries.sort(([a], [b]) => a.localeCompare(b))
multipart.sort()
unenveloped.sort()

const out = `// This file is auto-generated by scripts/gen-endpoints.mjs
import type * as T from './types.gen'

/** Every Admin operation, keyed \`'METHOD /path'\`, with its generated request type. */
export interface Endpoints {
${entries.map(([key, name]) => `  '${key}': T.${name}`).join('\n')}
}

/** Operations whose body is sent as multipart/form-data. */
export const MULTIPART_ENDPOINTS: ReadonlySet<string> = new Set([
${multipart.map(key => `  '${key}',`).join('\n')}
])

/** Operations whose success body isn't a \`ResponseMsg*\` envelope; the client reads it as it is. */
export const UNENVELOPED_ENDPOINTS: ReadonlySet<string> = new Set([
${unenveloped.map(key => `  '${key}',`).join('\n')}
])
`

await writeFile(new URL('../app/api/generated/endpoints.gen.ts', import.meta.url), out)
console.log(`Wrote ${entries.length} endpoints (${multipart.length} multipart, ${unenveloped.length} unenveloped) to app/api/generated/endpoints.gen.ts`)
