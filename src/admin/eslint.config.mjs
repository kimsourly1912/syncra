// @ts-check
import nuxtUI from '@nuxt/ui/eslint'
import boundaries from 'eslint-plugin-boundaries'
import withNuxt from './.nuxt/eslint.config.mjs'

// Admin's conventions (AGENTS.md, docs/), checked here so a change that breaks one fails lint
// instead of relying on someone reading the docs.

/** A feature is used through its public `index.ts`, never a file inside it (docs/architecture.md). */
const FEATURE_INTERNALS = {
  group: ['@/features/*/**'],
  message: 'Import a feature through its index (`@/features/<feature>`). Inside a feature, use relative imports.',
}

/** MSW and its generated handlers are for tests only (test/support/msw.ts, decision 0021). */
const TEST_ONLY = {
  group: ['msw', 'msw/*', '@/api/generated/msw.gen'],
  message: 'Test-only: use MSW in tests (`tests/`, test/support), never in app code.',
}

const TILDE = {
  group: ['~/*', '~~/*'],
  message: 'Use `@/` imports (decision 0004).',
}

export default withNuxt(
  // Generated by `pnpm --filter admin api:gen`; never edited by hand.
  { ignores: ['app/api/generated/**'] },

  // The architecture as a map (docs/architecture.md → Layers, decision 0021): every folder is a
  // layer, each feature its own element, and an import is allowed only along a listed edge. Shared
  // code (components, composables, utils, api) never imports a feature; another feature is used
  // only through its index.ts. A new folder needs a line here, or its imports fail.
  {
    files: ['app/**/*.{ts,vue}', 'test/**/*.ts'],
    plugins: { boundaries },
    settings: {
      'boundaries/root-path': import.meta.dirname,
      'import/resolver': { typescript: { project: './.nuxt/tsconfig.app.json', alwaysTryTypes: true } },
      'boundaries/elements': [
        { type: 'feature', pattern: 'app/features/*', capture: ['name'], partialMatch: false },
        { type: 'api', pattern: 'app/api', partialMatch: false },
        { type: 'component', pattern: 'app/components', partialMatch: false },
        { type: 'composable', pattern: 'app/composables', partialMatch: false },
        { type: 'util', pattern: 'app/utils', partialMatch: false },
        { type: 'page', pattern: 'app/pages', partialMatch: false },
        { type: 'layout', pattern: 'app/layouts', partialMatch: false },
        { type: 'wiring', pattern: ['app/plugins', 'app/middleware'], partialMatch: false },
        { type: 'test-support', pattern: 'test/support', partialMatch: false },
        { type: 'test', pattern: ['test/app-shell', 'test/e2e'], partialMatch: false },
        // app.vue, error.vue, app.config.ts, types/: what's left directly under app/.
        { type: 'shell', pattern: 'app', partialMatch: false },
      ],
      // A test beside the code (`<folder>/tests/`) belongs to that folder's element, and may also
      // use the shared test helpers.
      'boundaries/files': [{ pattern: '**/tests/**', category: 'test' }],
    },
    rules: {
      'boundaries/dependencies': ['error', {
        default: 'disallow',
        message: '{{ from.element.types.[0] }} can\'t import {{ to.element.types.[0] }} (docs/architecture.md → Layers)',
        policies: [
          // Anything may import npm packages and its own files.
          { allow: { to: { module: { origin: ['external', 'core'] } } } },
          { allow: { dependency: { relationship: { to: 'internal' } } } },
          // Shared code: never a feature.
          { from: { element: { type: 'composable' } }, allow: { to: { element: { types: ['api', 'component', 'util'] } } } },
          { from: { element: { type: 'component' } }, allow: { to: { element: { types: ['api', 'composable', 'util'] } } } },
          { from: { element: { type: 'util' } }, allow: { to: { element: { types: ['api'] } } } },
          // Features: the shared layers, and another feature through its index.ts.
          { from: { element: { type: 'feature' } }, allow: { to: { element: { types: ['api', 'component', 'composable', 'util'] } } } },
          { from: { element: { type: 'feature' } }, allow: { to: { element: { type: 'feature', fileInternalPath: 'index.ts' } } } },
          // Routes and app wiring render or start features.
          { from: { element: { types: ['page', 'layout', 'shell', 'wiring'] } }, allow: { to: { element: { types: ['component', 'composable', 'util'] } } } },
          { from: { element: { types: ['page', 'layout', 'shell', 'wiring'] } }, allow: { to: { element: { type: 'feature', fileInternalPath: 'index.ts' } } } },
          { from: { element: { type: 'wiring' } }, allow: { to: { element: { type: 'api' } } } },
          { from: { file: { categories: 'test' } }, allow: { to: { element: { type: 'test-support' } } } },
          // Tests outside app/ drive the app from outside.
          { from: { element: { type: 'test-support' } }, allow: { to: { element: { type: 'api' } } } },
          { from: { element: { type: 'test' } }, allow: { to: { element: { types: ['api', 'layout', 'wiring', 'test-support'] } } } },
          { from: { element: { type: 'test' } }, allow: { to: { element: { type: 'feature', fileInternalPath: 'index.ts' } } } },
        ],
      }],
    },
  },

  // Nuxt UI's rules for Tailwind classes, checked against the theme in tailwind.css: raw palette
  // colors (`text-gray-500` → `text-muted`) and classes that set the same property (`p-2 p-4`).
  // Registered here rather than with `ui: { eslint }` in nuxt.config: on Windows that generates an
  // import of a bare `C:/…` path, which Node refuses. `colors` mirrors app.config.ts.
  nuxtUI({
    entryPoint: 'app/assets/css/tailwind.css',
    colors: { primary: 'brand', secondary: 'blue', success: 'green', info: 'blue', warning: 'yellow', error: 'red', neutral: 'slate' },
    rules: { 'no-palette-colors': 'error', 'no-conflicting-classes': 'error' },
  }),

  {
    files: ['app/**/*.{ts,vue}'],
    rules: {
      'no-restricted-imports': ['error', { patterns: [TILDE, FEATURE_INTERNALS, TEST_ONLY] }],
      // Semantic tokens only, so light and dark both work (docs/ui.md → Foundation). `text-dimmed`
      // is 2.6:1 on white, below WCAG AA: use `text-muted` (decision 0021).
      'vue/no-restricted-class': ['error', 'bg-white', 'bg-black', '/^dark:/', '/\\[#[0-9a-fA-F]{3,8}\\]/', '/(^|:)text-dimmed$/'],
      'vue/no-restricted-syntax': ['error', {
        // Validation runs on submit, not on blur (docs/forms.md).
        selector: 'VElement[rawName="UForm"]:not(:has(VAttribute[directive=true][key.argument.name="validate-on"]))',
        message: 'Every UForm sets `:validate-on="[]"` (docs/forms.md).',
      }, {
        // Nuxt UI's class merge can't see that `row-link` replaces ULink's own colors (docs/ui.md → Rows).
        selector: 'VElement[rawName="ULink"] > VStartTag:has(VAttribute[directive=false][key.name="class"][value.value=/(^|\\s)row-link(\\s|$)/]):not(:has(VAttribute[directive=false][key.name="raw"]))',
        message: 'A ULink with `row-link` sets `raw`, or its own link color wins (docs/ui.md → Rows).',
      }, {
        // A button that shows only an icon has no name for a screen reader (docs/ui.md).
        // `children.length=0` keeps `:has` to the button's own attributes; a `v-bind="…"` spread may carry the name.
        selector: 'VElement[rawName="UButton"][children.length=0]:matches(:has(VAttribute[key.name="icon"]), :has(VAttribute[key.argument.name="icon"])):not(:has(VAttribute[key.name=/^(label|aria-label)$/])):not(:has(VAttribute[key.argument.name=/^(label|aria-label)$/])):not(:has(VAttribute[directive=true][key.name.name="bind"][key.argument=null]))',
        message: 'An icon-only UButton sets `aria-label` (or `label`), so screen readers can name it (docs/ui.md).',
      }],
    },
  },

  // A promise is awaited, or marked `void` where nothing waits on purpose: a forgotten `await` on
  // `router.push` or `refresh()` is a silent bug. These two rules need type information (the
  // project's tsconfig), which adds a few seconds to a commit's lint.
  {
    files: ['app/**/*.{ts,vue}', 'test/**/*.ts'],
    languageOptions: {
      parserOptions: { projectService: true, tsconfigRootDir: import.meta.dirname, extraFileExtensions: ['.vue'] },
    },
    rules: {
      '@typescript-eslint/no-floating-promises': 'error',
      // An event handler (`@click`, `onSelect`) may return a promise; Vue doesn't wait on it.
      '@typescript-eslint/no-misused-promises': ['error', { checksVoidReturn: { attributes: false, properties: false } }],
    },
  },

  // Routes, shared components, and layouts don't call the API: a feature composable does.
  {
    files: ['app/pages/**/*.vue', 'app/components/**/*.vue', 'app/layouts/**/*.vue'],
    ignores: ['app/components/alert/AlertApiError.vue'],
    rules: {
      'no-restricted-imports': ['error', {
        patterns: [TILDE, FEATURE_INTERNALS, TEST_ONLY],
        paths: [{ name: '@/api', message: 'Call the API from a feature composable (docs/data-access.md).' }],
      }],
    },
  },

  // A page names itself in its meta, which the tab and the sidebar read (docs/architecture.md).
  {
    files: ['app/pages/**/*.vue'],
    rules: {
      'no-restricted-syntax': ['error', {
        selector: 'CallExpression[callee.name="useHead"] > ObjectExpression > Property[key.name="title"]',
        message: 'Name the page with `definePageMeta({ title })`, which the tab and the sidebar read (docs/architecture.md).',
      }],
    },
  },

  // A feature's components get data from its composables; only composables call `api`. Types and
  // `errorMessage` are fine.
  {
    files: ['app/features/*/components/**/*.vue'],
    rules: {
      'no-restricted-imports': ['error', {
        patterns: [TILDE, FEATURE_INTERNALS, TEST_ONLY],
        paths: [{ name: '@/api', importNames: ['api'], message: 'Call `api` from the feature\'s composable, inside useApiQuery or useApiMutation (docs/data-access.md).' }],
      }],
    },
  },

  // Feature code: `useApiMutation` handles failures, and navigation uses a router captured in setup.
  {
    files: ['app/features/**/*.{ts,vue}'],
    // Tests drive the code from outside, so they may catch what it throws.
    ignores: ['app/features/session/**', 'app/**/tests/**'],
    rules: {
      'no-restricted-syntax': ['error',
        { selector: 'TryStatement', message: 'No try/catch in features: wrap the request in useApiMutation or useApiQuery (docs/data-access.md).' },
        { selector: 'CallExpression[callee.name="navigateTo"]', message: 'Use a router captured in setup (`useRouter()`), not navigateTo (docs/data-access.md).' },
        { selector: 'CallExpression[callee.name=/^(useAsyncData|useLazyAsyncData|useFetch|useLazyFetch|\\$fetch)$/]', message: 'Read with useApiQuery and `api` from `@/api`, which cancel stale loads and parse a model (docs/data-access.md).' },
      ],
    },
  },

  // Errors the team must see go to `reportAppError` (utils/report.ts), the one place that logs them.
  {
    files: ['app/**/*.{ts,vue}'],
    ignores: ['app/utils/report.ts', 'app/**/tests/**'],
    rules: { 'no-console': ['error', { allow: ['warn'] }] },
  },

  // Tests import the app as app code does, and may use MSW: tests beside the code, and those outside
  // app/ (the app shell, shared helpers, e2e).
  {
    files: ['app/**/tests/**/*.ts', 'test/**/*.ts'],
    rules: {
      'no-restricted-imports': ['error', { patterns: [TILDE, FEATURE_INTERNALS] }],
    },
  },

  // Content that stays white in dark mode on purpose: a paper PDF page, and customer email HTML.
  {
    files: ['app/features/techpack-review/components/ReviewSourcePanel.vue', 'app/features/settings/components/EmailTemplateSettings.vue'],
    rules: { 'vue/no-restricted-class': 'off' },
  },
)
